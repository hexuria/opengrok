#!/usr/bin/env node
// Every atomic class a ported view names has to have its declaration shipped,
// or the view mounts unstyled: a flex column becomes stacked text, a card loses
// its surface, a heading falls back to the browser's 24px bold. The recovered
// renderer carries those declarations in one stylesheet; the ports copied a
// subset into hand-kept parity files and the rest never arrived (267 atoms on
// 2026-09-06, found because the mock-cards fixtures drew every card at once).
//
// This walks frontend/src for the atom names the ports use, subtracts the ones
// a frontend stylesheet already declares, and copies the remaining rules —
// declaration text and source order untouched — into one generated stylesheet.
// It reads the immutable renderer CSS and writes only under frontend/, which
// ships through stow, never through this repository.
//
//   node scripts/extract-recovered-atoms-css.mjs          write the stylesheet
//   node scripts/extract-recovered-atoms-css.mjs --check  exit 1 if it is stale
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const RECOVERED_CSS = "src/app/dist/renderer/assets/index-lCyB53CO.css";
export const RECOVERED_CSS_SHA256 = "5a25f934b7d3b7a55483cb5f2a1a05e21209aad0a09c82d07d2add054a6b7856";
export const OUTPUT = "frontend/src/recovered/ui/recovered-atoms.css";
const FRONTEND_SRC = "frontend/src";

// Atom names are hashed: a `sand-`/`ui-` prefix and 5–8 base-36 characters.
// Semantic names (`sand-border`) match the shape too; they are filtered out
// below because the recovered stylesheet has no single-class rule for them.
const ATOM_PATTERN = /\b(?:sand|ui)-[0-9a-z]{5,8}\b/g;
const ATOM_SELECTOR_PATTERN = /\.((?:sand|ui)-[0-9a-z]{5,8})\b/g;

function* walk(dir, extensions) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(full, extensions);
    else if (extensions.some((extension) => entry.name.endsWith(extension))) yield full;
  }
}

/** Top-level rules of a minified stylesheet, descending into @media/@supports/@layer/@container. */
export function parseRules(css) {
  const rules = [];
  const visit = (start, end, wrap) => {
    let index = start;
    while (index < end) {
      const open = css.indexOf("{", index);
      if (open < 0 || open >= end) break;
      const selector = css.slice(index, open).trim();
      let depth = 1;
      let close = open + 1;
      while (close < end && depth > 0) {
        if (css[close] === "{") depth += 1;
        else if (css[close] === "}") depth -= 1;
        close += 1;
      }
      const body = css.slice(open + 1, close - 1);
      if (/^@(media|supports|layer|container)\b/.test(selector)) visit(open + 1, close - 1, wrap == null ? selector : `${wrap}{${selector}`);
      else if (!selector.startsWith("@")) rules.push({ selector, body, wrap });
      index = close;
    }
  };
  visit(0, css.length, null);
  return rules;
}

export function collectAtoms(root = repoRoot) {
  const used = new Set();
  const declared = new Set();
  const src = path.join(root, FRONTEND_SRC);
  for (const file of walk(src, [".ts", ".tsx"])) {
    for (const atom of readFileSync(file, "utf8").match(ATOM_PATTERN) ?? []) used.add(atom);
  }
  for (const file of walk(src, [".css"])) {
    if (path.relative(root, file) === OUTPUT) continue;
    for (const match of readFileSync(file, "utf8").matchAll(ATOM_SELECTOR_PATTERN)) declared.add(match[1]);
  }
  return { used, declared };
}

export function renderStylesheet(root = repoRoot) {
  const css = readFileSync(path.join(root, RECOVERED_CSS), "utf8");
  const sha256 = createHash("sha256").update(css).digest("hex");
  // Every used atom, not only the ones no other stylesheet declares: atoms
  // that share a property (primary vs monochrome text color) resolve by
  // source order, and that order only holds if they sit in one stylesheet in
  // the recovered sequence. The hand-kept parity copies stay as they are and
  // this sheet, imported last, restates them in the right order.
  const { used } = collectAtoms(root);
  const wanted = new Set(used);
  const emitted = new Set();
  const lines = [];
  for (const rule of parseRules(css)) {
    const atoms = [...rule.selector.matchAll(ATOM_SELECTOR_PATTERN)].map((match) => match[1]);
    if (!atoms.some((atom) => wanted.has(atom))) continue;
    for (const atom of atoms) emitted.add(atom);
    const text = `${rule.selector}{${rule.body}}`;
    lines.push(rule.wrap == null ? text : `${rule.wrap}{${text}${"}".repeat(rule.wrap.split("{").length)}`);
  }
  const header = [
    "/* Generated by scripts/extract-recovered-atoms-css.mjs — do not edit by hand.",
    ` * @evidence ${RECOVERED_CSS}`,
    ` * Immutable CSS SHA-256: ${sha256}`,
    " * Every atomic class named by a ported view under frontend/src, copied verbatim",
    " * and in source order from the immutable renderer stylesheet so the ports mount",
    " * with their own styling and same-property atoms resolve as they ship. */",
    "",
  ];
  return { text: `${header.join("\n")}${lines.join("\n")}\n`, sha256, wanted, emitted, ruleCount: lines.length };
}

function main() {
  const check = process.argv.includes("--check");
  const recovered = path.join(repoRoot, RECOVERED_CSS);
  if (!existsSync(recovered)) {
    console.error(`missing ${RECOVERED_CSS}; restore the recovered renderer before regenerating`);
    process.exit(2);
  }
  const result = renderStylesheet(repoRoot);
  if (result.sha256 !== RECOVERED_CSS_SHA256) console.warn(`warning: ${RECOVERED_CSS} hashes to ${result.sha256}, not the pinned ${RECOVERED_CSS_SHA256}`);
  const unmatched = [...result.wanted].filter((atom) => !result.emitted.has(atom));
  const outputPath = path.join(repoRoot, OUTPUT);
  const current = existsSync(outputPath) ? readFileSync(outputPath, "utf8") : null;
  if (check) {
    if (current === result.text) { console.log(`${OUTPUT} is current (${result.ruleCount} rules)`); return; }
    console.error(`${OUTPUT} is stale; run node scripts/extract-recovered-atoms-css.mjs`);
    process.exit(1);
  }
  writeFileSync(outputPath, result.text);
  console.log(`${OUTPUT}: ${result.ruleCount} rules for ${result.emitted.size} atoms (${unmatched.length} names with no atomic rule, ignored)`);
}

if (process.argv[1] != null && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
